#!/usr/bin/env python3
"""Generate GCC/CMake build files from the Keil uVision project list.

Keil remains the source of truth for project membership.  This tool builds a
separate GCC view by replacing ARMCC-only pieces with files from
tools/build/gcc_support.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

import ProjectManifest


REPO_ROOT = ProjectManifest.REPO_ROOT
SUPPORT_ROOT = REPO_ROOT / "tools" / "build" / "gcc_support"
DEFAULT_OUT_ROOT = REPO_ROOT / "build" / "gcc"
GCC_COMPAT_HEADER = SUPPORT_ROOT / "arbatos_gcc_compat.h"
GCC_SYSCALLS_SOURCE = SUPPORT_ROOT / "syscalls_nosys.c"


def cmake_path(path: Path) -> str:
    return path.resolve(strict=False).as_posix()


def quote(value: str) -> str:
    return '"' + value.replace("\\", "/").replace('"', '\\"') + '"'


def rel_repo(path: Path) -> str:
    return ProjectManifest.repo_path(path)


def project_cpu(manifest: dict[str, Any]) -> dict[str, str]:
    text = f"{manifest.get('device') or ''} {manifest.get('cpu') or ''}"
    if "Cortex-M7" in text or "STM32H7" in text:
        return {
            "name": "cortex-m7",
            "flags": "-mcpu=cortex-m7 -mthumb -mfpu=fpv5-d16 -mfloat-abi=hard",
            "freertos_port": "ARM_CM7/r0p1",
        }
    return {
        "name": "cortex-m4",
        "flags": "-mcpu=cortex-m4 -mthumb -mfpu=fpv4-sp-d16 -mfloat-abi=hard",
        "freertos_port": "ARM_CM4F",
    }


def parse_scatter_memory(manifest: dict[str, Any]) -> dict[str, Any]:
    scatter_entries = manifest.get("scatter_files") or []
    flash = {"name": "FLASH", "origin": 0x08000000, "length": 0x00100000}
    ram_regions: list[dict[str, Any]] = []

    for entry in scatter_entries:
        repo = entry.get("repo_path")
        if not repo:
            continue
        path = REPO_ROOT / repo
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        flash_match = re.search(r"LR_IROM1\s+(0x[0-9A-Fa-f]+)\s+(0x[0-9A-Fa-f]+)", text)
        if flash_match:
            flash = {
                "name": "FLASH",
                "origin": int(flash_match.group(1), 16),
                "length": int(flash_match.group(2), 16),
            }
        for match in re.finditer(r"RW_(IRAM\d+)\s+(0x[0-9A-Fa-f]+)\s+(0x[0-9A-Fa-f]+)", text):
            ram_regions.append(
                {
                    "name": match.group(1),
                    "origin": int(match.group(2), 16),
                    "length": int(match.group(3), 16),
                }
            )
        break

    if not ram_regions:
        cpu_text = manifest.get("cpu") or ""
        for match in re.finditer(r"IRAM\d*\(0x([0-9A-Fa-f]+)-0x([0-9A-Fa-f]+)\)", cpu_text):
            origin = int(match.group(1), 16)
            end = int(match.group(2), 16)
            ram_regions.append({"name": f"IRAM{len(ram_regions) + 1}", "origin": origin, "length": end - origin + 1})

    if not ram_regions:
        ram_regions.append({"name": "IRAM1", "origin": 0x20000000, "length": 0x00020000})

    primary = max(ram_regions, key=lambda item: item["length"])
    extras = [item for item in ram_regions if item is not primary]
    return {"flash": flash, "primary_ram": primary, "extra_ram": extras}


def render_linker_script(manifest: dict[str, Any]) -> str:
    memory = parse_scatter_memory(manifest)
    flash = memory["flash"]
    ram = memory["primary_ram"]
    extras = memory["extra_ram"]

    lines = [
        "/* Generated by tools/build/GccProject.py. */",
        "ENTRY(Reset_Handler)",
        "",
        "MEMORY",
        "{",
        f"  FLASH (rx)  : ORIGIN = 0x{flash['origin']:08X}, LENGTH = 0x{flash['length']:X}",
        f"  RAM (xrw)   : ORIGIN = 0x{ram['origin']:08X}, LENGTH = 0x{ram['length']:X}",
    ]
    for index, region in enumerate(extras, start=2):
        name = "CCMRAM" if region["origin"] == 0x10000000 else f"RAM{index}"
        region["ld_name"] = name
        lines.append(f"  {name} (xrw) : ORIGIN = 0x{region['origin']:08X}, LENGTH = 0x{region['length']:X}")
    lines.extend(
        [
            "}",
            "",
            "_estack = ORIGIN(RAM) + LENGTH(RAM);",
            "",
            "SECTIONS",
            "{",
            "  .isr_vector :",
            "  {",
            "    . = ALIGN(4);",
            "    KEEP(*(.isr_vector))",
            "    . = ALIGN(4);",
            "  } > FLASH",
            "",
            "  .text :",
            "  {",
            "    . = ALIGN(4);",
            "    *(.text)",
            "    *(.text*)",
            "    *(.glue_7)",
            "    *(.glue_7t)",
            "    *(.eh_frame)",
            "    KEEP(*(.init))",
            "    KEEP(*(.fini))",
            "    . = ALIGN(4);",
            "    _etext = .;",
            "  } > FLASH",
            "",
            "  .rodata :",
            "  {",
            "    . = ALIGN(4);",
            "    *(.rodata)",
            "    *(.rodata*)",
            "    . = ALIGN(4);",
            "  } > FLASH",
            "",
            "  .ARM.extab : { *(.ARM.extab* .gnu.linkonce.armextab.*) } > FLASH",
            "  .ARM :",
            "  {",
            "    __exidx_start = .;",
            "    *(.ARM.exidx*)",
            "    __exidx_end = .;",
            "  } > FLASH",
            "",
            "  .preinit_array :",
            "  {",
            "    PROVIDE_HIDDEN(__preinit_array_start = .);",
            "    KEEP(*(.preinit_array*))",
            "    PROVIDE_HIDDEN(__preinit_array_end = .);",
            "  } > FLASH",
            "  .init_array :",
            "  {",
            "    PROVIDE_HIDDEN(__init_array_start = .);",
            "    KEEP(*(SORT(.init_array.*)))",
            "    KEEP(*(.init_array*))",
            "    PROVIDE_HIDDEN(__init_array_end = .);",
            "  } > FLASH",
            "  .fini_array :",
            "  {",
            "    PROVIDE_HIDDEN(__fini_array_start = .);",
            "    KEEP(*(SORT(.fini_array.*)))",
            "    KEEP(*(.fini_array*))",
            "    PROVIDE_HIDDEN(__fini_array_end = .);",
            "  } > FLASH",
            "",
            "  _sidata = LOADADDR(.data);",
            "  .data :",
            "  {",
            "    . = ALIGN(4);",
            "    _sdata = .;",
            "    *(.data)",
            "    *(.data*)",
            "    . = ALIGN(4);",
            "    _edata = .;",
            "  } > RAM AT > FLASH",
            "",
            "  .bss (NOLOAD) :",
            "  {",
            "    . = ALIGN(4);",
            "    _sbss = .;",
            "    __bss_start__ = _sbss;",
            "    *(.bss)",
            "    *(.bss*)",
            "    *(COMMON)",
            "    . = ALIGN(4);",
            "    _ebss = .;",
            "    __bss_end__ = _ebss;",
            "  } > RAM",
        ]
    )

    for region in extras:
        name = region.get("ld_name") or "RAM2"
        if name == "CCMRAM":
            lines.extend(
                [
                    "",
                    "  .ccmram (NOLOAD) :",
                    "  {",
                    "    . = ALIGN(4);",
                    "    *(.ccmram)",
                    "    *(.ccmram*)",
                    "    . = ALIGN(4);",
                    "  } > CCMRAM",
                ]
            )
        else:
            lines.extend(
                [
                    "",
                    f"  .{name.lower()} (NOLOAD) :",
                    "  {",
                    "    . = ALIGN(4);",
                    f"    *(.{name.lower()})",
                    f"    *(.{name.lower()}*)",
                    "    . = ALIGN(4);",
                    f"  }} > {name}",
                ]
            )

    lines.extend(
        [
            "",
            "  ._user_heap_stack (NOLOAD) :",
            "  {",
            "    . = ALIGN(8);",
            "    PROVIDE(end = .);",
            "    PROVIDE(_end = .);",
            "    . = ALIGN(8);",
            "  } > RAM",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def parse_startup_vectors(path: Path) -> list[str]:
    vectors: list[str] = []
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        match = re.search(r"\bDCD\s+([A-Za-z_][A-Za-z0-9_]*|0)\b", line)
        if match:
            vectors.append(match.group(1))
    if len(vectors) < 16:
        raise ValueError(f"startup vector table looks too small: {rel_repo(path)}")
    vectors[0] = "_estack"
    return vectors


def render_startup(path: Path, cpu_name: str) -> str:
    vectors = parse_startup_vectors(path)
    handlers = sorted({item for item in vectors if item not in {"0", "_estack", "Reset_Handler"}})
    vector_rows = [f"  .word {item}" for item in vectors]
    weak_rows = [f"  .weak {name}\n  .thumb_set {name}, Default_Handler" for name in handlers]
    return "\n".join(
        [
            "/* Generated by tools/build/GccProject.py from the Keil startup file. */",
            "  .syntax unified",
            f"  .cpu {cpu_name}",
            "  .thumb",
            "",
            "  .section .isr_vector,\"a\",%progbits",
            "  .global __Vectors",
            "  .global g_pfnVectors",
            "__Vectors:",
            "g_pfnVectors:",
            *vector_rows,
            "",
            "  .text",
            "  .thumb",
            "  .global Reset_Handler",
            "  .type Reset_Handler, %function",
            "Reset_Handler:",
            "  ldr r0, =_estack",
            "  mov sp, r0",
            "  bl SystemInit",
            "  bl __libc_init_array",
            "  bl main",
            "LoopForever:",
            "  b LoopForever",
            "",
            "  .global Default_Handler",
            "  .type Default_Handler, %function",
            "Default_Handler:",
            "  b Default_Handler",
            "",
            *weak_rows,
            "",
        ]
    )


def classify_binary_library(path_text: str) -> str | None:
    name = Path(path_text.replace("\\", "/")).name.lower()
    if name == "ahrs.lib":
        return "ahrs"
    if name == "arm_cortexm4lf_math.lib":
        return "arm_math"
    return None


def build_gcc_view(manifest: dict[str, Any], out_dir: Path) -> dict[str, Any]:
    cpu = project_cpu(manifest)
    support_sources: list[Path] = []
    sources: list[Path] = []
    includes: list[Path] = []
    blockers: list[str] = []
    replacements: list[str] = []

    freertos_port_dir = SUPPORT_ROOT / "freertos" / "portable" / "GCC" / cpu["freertos_port"]
    if not freertos_port_dir.exists():
        blockers.append(f"missing FreeRTOS GCC port: {rel_repo(freertos_port_dir)}")
    if not GCC_COMPAT_HEADER.exists():
        blockers.append(f"missing GCC compatibility header: {rel_repo(GCC_COMPAT_HEADER)}")
    if GCC_SYSCALLS_SOURCE.exists():
        support_sources.append(GCC_SYSCALLS_SOURCE)
    else:
        blockers.append(f"missing GCC syscall stubs: {rel_repo(GCC_SYSCALLS_SOURCE)}")

    if cpu["name"] == "cortex-m7":
        for support_include in h7_cmsis_support_includes():
            if support_include.exists():
                includes.append(support_include)
            else:
                blockers.append(f"missing H7 CMSIS support include: {rel_repo(support_include)}")

    for entry in manifest["files"]:
        repo = entry.get("repo_path")
        kind = entry.get("kind")
        path_text = entry.get("path", "")
        if kind == "c":
            if "/portable/RVDS/" in path_text:
                support_sources.append(freertos_port_dir / "port.c")
                replacements.append("FreeRTOS RVDS portable -> FreeRTOS GCC portable")
                continue
            if repo:
                sources.append(REPO_ROOT / repo)
        elif kind == "library":
            replacement = classify_binary_library(path_text)
            if replacement == "ahrs":
                support_sources.append(SUPPORT_ROOT / "algorithm" / "AHRS_gcc.c")
                replacements.append("AHRS.lib -> GCC AHRS source")
            elif replacement == "arm_math":
                support_sources.append(SUPPORT_ROOT / "algorithm" / "arm_math_compat.c")
                replacements.append("arm_cortexM4lf_math.lib -> GCC math fallback")
            else:
                blockers.append(f"unsupported binary library: {path_text}")

    startup_entries = [entry for entry in manifest["files"] if entry.get("kind") == "asm" and entry.get("repo_path")]
    if not startup_entries:
        blockers.append("missing Keil startup file to translate")
        startup_path = None
    else:
        startup_path = REPO_ROOT / startup_entries[0]["repo_path"]

    for entry in manifest["include_dirs"]:
        if entry.get("external"):
            continue
        path_text = entry.get("path", "")
        if "/portable/RVDS/" in path_text:
            includes.append(freertos_port_dir)
            continue
        repo = entry.get("repo_path")
        if repo:
            includes.append(REPO_ROOT / repo)

    if blockers:
        return {
            "project": manifest["project"],
            "generated": False,
            "out_dir": rel_repo(out_dir),
            "blockers": sorted(set(blockers)),
            "replacements": sorted(set(replacements)),
        }

    out_dir.mkdir(parents=True, exist_ok=True)
    startup_out = out_dir / "startup_gcc.S"
    linker_out = out_dir / "linker.ld"
    toolchain_out = out_dir / "arm-none-eabi-gcc.cmake"
    cmake_out = out_dir / "CMakeLists.txt"

    assert startup_path is not None
    startup_out.write_text(render_startup(startup_path, cpu["name"]), encoding="utf-8", newline="\n")
    linker_out.write_text(render_linker_script(manifest), encoding="utf-8", newline="\n")
    toolchain_out.write_text(render_toolchain_file(), encoding="utf-8", newline="\n")
    cmake_out.write_text(
        render_cmake(manifest, cpu, sources + sorted(set(support_sources)), includes, startup_out, linker_out),
        encoding="utf-8",
        newline="\n",
    )

    return {
        "project": manifest["project"],
        "generated": True,
        "out_dir": rel_repo(out_dir),
        "blockers": [],
        "replacements": sorted(set(replacements)),
        "configure": f"cmake -S {rel_repo(out_dir)} -B {rel_repo(out_dir / 'build')} -G Ninja -DCMAKE_TOOLCHAIN_FILE=arm-none-eabi-gcc.cmake",
        "build": f"cmake --build {rel_repo(out_dir / 'build')}",
    }


def render_toolchain_file() -> str:
    return "\n".join(
        [
            "# Generated by tools/build/GccProject.py.",
            "set(CMAKE_SYSTEM_NAME Generic)",
            "set(CMAKE_SYSTEM_PROCESSOR arm)",
            "set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)",
            "",
            "find_program(CMAKE_C_COMPILER arm-none-eabi-gcc REQUIRED)",
            "find_program(CMAKE_ASM_COMPILER arm-none-eabi-gcc REQUIRED)",
            "find_program(CMAKE_OBJCOPY arm-none-eabi-objcopy REQUIRED)",
            "find_program(CMAKE_SIZE arm-none-eabi-size REQUIRED)",
            "",
        ]
    )


def h7_cmsis_support_includes() -> list[Path]:
    return [
        SUPPORT_ROOT / "cmsis" / "Include",
        SUPPORT_ROOT / "cmsis_device_h7" / "Include",
    ]


def render_cmake(
    manifest: dict[str, Any],
    cpu: dict[str, str],
    sources: list[Path],
    includes: list[Path],
    startup: Path,
    linker: Path,
) -> str:
    project_name = manifest["project"]
    defines = [
        value
        for value in manifest["defines"]
        if value not in {"__CC_ARM"} and not value.startswith("__CC_ARM=")
    ]
    source_lines = [f"  {quote(cmake_path(startup))}"]
    for path in sorted({path.resolve(strict=False) for path in sources}, key=lambda item: item.as_posix().casefold()):
        source_lines.append(f"  {quote(cmake_path(path))}")

    include_lines = [
        f"  {quote(cmake_path(path))}"
        for path in sorted({path.resolve(strict=False) for path in includes}, key=lambda item: item.as_posix().casefold())
    ]
    define_lines = [f"  {item}" for item in sorted(set(defines))]
    flag_items = cpu["flags"].split()
    compile_options = flag_items + [
        "-include",
        cmake_path(GCC_COMPAT_HEADER),
        "-ffunction-sections",
        "-fdata-sections",
        "-Wall",
        "-Wextra",
        "-Wno-unused-parameter",
        "-Wno-missing-field-initializers",
    ]
    link_options = flag_items + [
        f"-T{cmake_path(linker)}",
        "-Wl,--gc-sections",
        f"-Wl,-Map=${{CMAKE_CURRENT_BINARY_DIR}}/{project_name}.map",
        "-Wl,--no-warn-rwx-segments",
        "--specs=nano.specs",
    ]

    return "\n".join(
        [
            "# Generated by tools/build/GccProject.py. Do not edit by hand.",
            "cmake_minimum_required(VERSION 3.20)",
            f"project(ARBATOS_{project_name} C ASM)",
            "",
            f"add_executable({project_name}.elf",
            *source_lines,
            ")",
            "",
            f"target_include_directories({project_name}.elf PRIVATE",
            *include_lines,
            ")",
            "",
            f"target_compile_definitions({project_name}.elf PRIVATE",
            *define_lines,
            ")",
            "",
            f"target_compile_options({project_name}.elf PRIVATE",
            *[f"  {item}" for item in compile_options],
            ")",
            "",
            f"target_link_options({project_name}.elf PRIVATE",
            *[f"  {quote(item) if ' ' in item else item}" for item in link_options],
            ")",
            "",
            f"target_link_libraries({project_name}.elf PRIVATE",
            "  m",
            ")",
            "",
            f"add_custom_command(TARGET {project_name}.elf POST_BUILD",
            f"  COMMAND ${{CMAKE_SIZE}} $<TARGET_FILE:{project_name}.elf>",
            f"  COMMAND ${{CMAKE_OBJCOPY}} -O ihex $<TARGET_FILE:{project_name}.elf> {project_name}.hex",
            f"  COMMAND ${{CMAKE_OBJCOPY}} -O binary $<TARGET_FILE:{project_name}.elf> {project_name}.bin",
            ")",
            "",
        ]
    )


def selected_manifests(args: argparse.Namespace) -> list[dict[str, Any]]:
    paths = ProjectManifest.select_projects(args)
    return [ProjectManifest.load_manifest(path) for path in paths]


def print_human(results: list[dict[str, Any]]) -> None:
    print("ARBATOS GCC build generator")
    print(f"repo: {REPO_ROOT}")
    for result in results:
        print("")
        print(f"{result['project']}: {'generated' if result['generated'] else 'blocked'}")
        print(f"  out: {result['out_dir']}")
        for replacement in result["replacements"]:
            print(f"  replacement: {replacement}")
        for blocker in result["blockers"]:
            print(f"  blocker: {blocker}")
        if result.get("configure"):
            print(f"  configure: {result['configure']}")
            print(f"  build: {result['build']}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", help="Project name, for example HERO-C.")
    parser.add_argument("--all", action="store_true", help="Generate all projects. This is the default.")
    parser.add_argument("--out-root", default=str(DEFAULT_OUT_ROOT), help="Output root. Default: build/gcc.")
    parser.add_argument("--json", action="store_true", help="Print JSON.")
    parser.add_argument("--check-only", action="store_true", help="Validate support without writing generated files.")
    args = parser.parse_args(argv)

    manifests = selected_manifests(args)
    out_root = Path(args.out_root).resolve(strict=False)
    results = []
    for manifest in manifests:
        out_dir = out_root / manifest["project"]
        if args.check_only:
            temp = build_gcc_view_check_only(manifest, out_dir)
            results.append(temp)
        else:
            results.append(build_gcc_view(manifest, out_dir))

    if args.json:
        print(json.dumps({"results": results}, indent=2))
    else:
        print_human(results)

    return 1 if any(result["blockers"] for result in results) else 0


def build_gcc_view_check_only(manifest: dict[str, Any], out_dir: Path) -> dict[str, Any]:
    cpu = project_cpu(manifest)
    freertos_port_dir = SUPPORT_ROOT / "freertos" / "portable" / "GCC" / cpu["freertos_port"]
    blockers: list[str] = []
    replacements: list[str] = []

    if not freertos_port_dir.exists():
        blockers.append(f"missing FreeRTOS GCC port: {rel_repo(freertos_port_dir)}")
    if not GCC_COMPAT_HEADER.exists():
        blockers.append(f"missing GCC compatibility header: {rel_repo(GCC_COMPAT_HEADER)}")
    if not GCC_SYSCALLS_SOURCE.exists():
        blockers.append(f"missing GCC syscall stubs: {rel_repo(GCC_SYSCALLS_SOURCE)}")

    if not any(entry.get("kind") == "asm" and entry.get("repo_path") for entry in manifest["files"]):
        blockers.append("missing Keil startup file to translate")

    if cpu["name"] == "cortex-m7":
        for support_include in h7_cmsis_support_includes():
            if not support_include.exists():
                blockers.append(f"missing H7 CMSIS support include: {rel_repo(support_include)}")

    for entry in manifest["files"]:
        if entry.get("kind") != "library":
            continue
        replacement = classify_binary_library(entry.get("path", ""))
        if replacement == "ahrs":
            if not (SUPPORT_ROOT / "algorithm" / "AHRS_gcc.c").exists():
                blockers.append("missing GCC AHRS source")
            replacements.append("AHRS.lib -> GCC AHRS source")
        elif replacement == "arm_math":
            if not (SUPPORT_ROOT / "algorithm" / "arm_math_compat.c").exists():
                blockers.append("missing GCC math fallback")
            replacements.append("arm_cortexM4lf_math.lib -> GCC math fallback")
        else:
            blockers.append(f"unsupported binary library: {entry.get('path', '')}")

    try:
        startup_entry = next(entry for entry in manifest["files"] if entry.get("kind") == "asm" and entry.get("repo_path"))
        parse_startup_vectors(REPO_ROOT / startup_entry["repo_path"])
        render_linker_script(manifest)
    except (StopIteration, OSError, ValueError) as exc:
        blockers.append(str(exc))

    return {
        "project": manifest["project"],
        "generated": len(blockers) == 0,
        "out_dir": rel_repo(out_dir),
        "blockers": sorted(set(blockers)),
        "replacements": sorted(set(replacements + ["FreeRTOS RVDS portable -> FreeRTOS GCC portable"])),
    }


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
